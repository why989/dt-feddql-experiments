"""Deployment model shared by the simulator, the digital twin, and the policies.

This module makes three things explicit that the earlier release left implicit,
and it is the reason the learned policy is no longer degenerate:

1. **Node-level action space.**  ``A = {L, e1, e2, e3, C}`` exactly as defined in
   the manuscript.  The DQN therefore has five outputs rather than three; the
   five entries are the node-level execution locations.

2. **Heterogeneous edge tier.**  The three edge nodes differ in clock frequency
   and uplink bandwidth, so they are not interchangeable.

3. **Finite service capacity (Eq. 11 of the manuscript).**  Every execution
   location is a finite server.  Pushing the whole workload onto one location
   raises its measured arrival rate towards its service rate, and the M/M/1
   waiting time of Eq. (11) then grows without bound, so "offload everything to
   the fastest edge node" is no longer free.  The utilisation ``rho_m`` and the
   queueing delay are exposed to the agent, which is what allows a
   load-balancing policy to be learned rather than assumed.
"""

from __future__ import annotations

from collections import deque
from typing import Dict, List, Tuple

# --------------------------------------------------------------------------
# Action space (node level)
# --------------------------------------------------------------------------

ACTION_MAP: Dict[int, str] = {
    0: "terminal",
    1: "edge_1",
    2: "edge_2",
    3: "edge_3",
    4: "cloud",
}

ACTION_ID: Dict[str, int] = {
    "terminal": 0,
    "edge_1": 1,
    "edge_2": 2,
    "edge_3": 3,
    "cloud": 4,
    # Legacy alias.  Older scripts refer to a single "edge" action; it now
    # denotes the primary edge node.  Prefer EDGE_ACTION_IDS in new code.
    "edge": 1,
}

EDGE_ACTION_IDS: Tuple[int, ...] = (1, 2, 3)
NUM_ACTIONS: int = len(ACTION_MAP)
EDGE_ACTION_NAMES: Tuple[str, ...] = ("edge_1", "edge_2", "edge_3")

# --------------------------------------------------------------------------
# Heterogeneous edge deployment
# --------------------------------------------------------------------------

REFERENCE_EDGE_GHZ: float = 5.0

EDGE_NODE_SPECS: Tuple[Dict[str, object], ...] = (
    {"action": 1, "name": "edge_1", "freq_ghz": 5.0, "uplink_mbps": (40.0, 100.0)},
    {"action": 2, "name": "edge_2", "freq_ghz": 4.0, "uplink_mbps": (30.0, 80.0)},
    {"action": 3, "name": "edge_3", "freq_ghz": 3.0, "uplink_mbps": (20.0, 60.0)},
)

EDGE_NODE_BY_ACTION: Dict[int, Dict[str, object]] = {
    int(spec["action"]): spec for spec in EDGE_NODE_SPECS
}

# An edge task that is granted priority QoS is given reserved cores, which is
# modelled as the same non-linear core speed-up used before.
PRIORITY_QOS_SPEEDUP: float = 4.0 ** 0.7


def edge_node_speedup(action: int, priority_qos: bool = False) -> float:
    """Compute-clock speed-up of an execution location relative to the reference."""

    if int(action) == ACTION_ID["terminal"]:
        return 1.0
    spec = EDGE_NODE_BY_ACTION.get(int(action))
    if spec is None:
        # Cloud is elastic; the reference-model branch handles its own timing.
        return 1.0
    speedup = float(spec["freq_ghz"]) / REFERENCE_EDGE_GHZ
    if priority_qos:
        speedup *= PRIORITY_QOS_SPEEDUP
    return speedup


# --------------------------------------------------------------------------
# Finite service capacity -- measurement-driven M/M/1 (manuscript Eq. (11))
# --------------------------------------------------------------------------
#
# The workload is generated by four continuously sensing stations, each emitting
# one processing task every ``STATION_PERIOD_MS``.  That fixes the aggregate
# offered load seen by the shared edge/cloud tier.  The value is set so that the
# offered load is close to, but below, the aggregate edge capacity: a balanced
# allocation serves the whole stream within the deadlines, whereas concentrating
# every task on the fastest edge node drives lambda towards mu on that node and
# the Eq. (11) waiting time diverges.  That is the regime in which a
# load-balancing policy is worth learning.
N_STATIONS: int = 4
STATION_PERIOD_MS: float = 180.0
STATION_INTERVAL_MS: float = STATION_PERIOD_MS
AGGREGATE_ARRIVAL_RATE_PER_S: float = N_STATIONS * 1000.0 / STATION_PERIOD_MS
GLOBAL_INTERVAL_MS: float = 1000.0 / AGGREGATE_ARRIVAL_RATE_PER_S

# The arrival rate of a destination is measured over a sliding window of virtual
# time.  A *time* window (rather than a fixed number of samples) is what makes
# the estimate behave correctly at both ends of the range: a node that is being
# hammered reaches a high rate immediately, while a node the policy has backed
# away from drains back towards zero instead of carrying a stale "busy" label
# forever -- the failure mode that made the first load-aware policy lock onto a
# single edge node.
QUEUE_WINDOW_MS: float = 1500.0
QUEUE_MIN_WINDOW_MS: float = 300.0

# Eq. (11) of the manuscript:
#   rho_m(t) = min(lambda_m(t) / mu_m(t), rho_max)
#   T^q_m(t) = rho_m(t) / (mu_m(t) - lambda_m(t) + eps_q)
# The cap and the epsilon are the tabulated values (rho_max = 0.95,
# eps_q = 1e-3).  The extra clip only keeps a saturated node finite so that the
# downstream latency clip is not doing the work of the queueing model.
RHO_MAX: float = 0.95
EPS_Q: float = 1e-3
QUEUE_WAIT_CAP_MS: float = 400.0

# Backlog is normalised by this value before being exposed to the agent.
QUEUE_BACKLOG_NORM_MS: float = 60.0

# The cloud tier is elastic: it is not the queueing bottleneck, the two-hop
# backhaul is.  Its dispatch time is therefore modelled as a small constant.
CLOUD_DISPATCH_MS: float = 1.0

CLOUD_ACTION_ID: int = ACTION_ID["cloud"]
TERMINAL_ACTION_ID: int = ACTION_ID["terminal"]


class NetworkQueueingModel:
    """Measurement-driven M/M/1 queueing model of the execution locations.

    Every destination keeps its own virtual arrival clock, which is what makes
    the capacity model physically meaningful rather than cosmetic:

    * the **shared** tiers (the three edge nodes and the cloud) see the aggregate
      stream, so their clock advances once per decision at the aggregate rate;
    * a **station-local** CPU only sees the tasks that station itself generates,
      so its clock advances once per own task at the station rate.

    For every destination ``m`` the model retains the tasks actually committed
    to it inside a sliding time window and forms the quantities of Eq. (11)
    directly from the realised routing: ``lambda_m`` is the measured arrival rate
    in tasks per millisecond, ``mu_m = 1 / mean(service demand)`` is the measured
    service rate, ``rho_m`` is their ratio capped at ``rho_max``, and the
    queueing delay reported to the simulator is
    ``T^q_m = rho_m / (mu_m - lambda_m + eps_q)``.

    Nothing here is a configured constant.  Concentrating the workload on one
    edge node drives ``lambda_m`` towards ``mu_m`` and the waiting time diverges,
    which is exactly the effect the earlier release was missing: its
    ``simulate_task_execution`` was stateless, so "offload everything to the
    fastest edge node" cost nothing.
    """

    def __init__(
        self,
        window_ms: float = QUEUE_WINDOW_MS,
        min_window_ms: float = QUEUE_MIN_WINDOW_MS,
    ) -> None:
        self.window_ms = float(window_ms)
        self.min_window_ms = float(min_window_ms)
        self.arrivals: Dict[str, deque] = {}
        self.served: Dict[str, int] = {}
        self.busy_ms: Dict[str, float] = {}
        self.station_count: Dict[str, int] = {}
        self.rho: Dict[str, float] = {}
        self.tq: Dict[str, float] = {}
        self.horizon_ms: float = 0.0

    # -- helpers ---------------------------------------------------------
    @staticmethod
    def station_of(task) -> str:
        return str(task.get("station_name", "local"))

    @staticmethod
    def destination_key(task, action: int) -> str:
        action = int(action)
        if action == TERMINAL_ACTION_ID:
            return f"terminal::{NetworkQueueingModel.station_of(task)}"
        if action == CLOUD_ACTION_ID:
            return "cloud"
        return ACTION_MAP.get(action, str(action))

    def _clock_ms(self, key: str, task, global_index: int) -> float:
        """Current time on the clock that governs ``key``."""

        if key.startswith("terminal::"):
            return self.station_count.get(key[len("terminal::"):], 0) * STATION_INTERVAL_MS
        return float(global_index) * GLOBAL_INTERVAL_MS

    def effective_service_ms(self, action: int, service_ms: float) -> float:
        """Service demand seen by the server of ``action``."""

        if int(action) == CLOUD_ACTION_ID:
            return CLOUD_DISPATCH_MS
        return float(service_ms)

    # -- Eq. (11) --------------------------------------------------------
    def _window(self, key: str, now: float) -> List[Tuple[float, float]]:
        samples = self.arrivals.get(key)
        if not samples:
            return []
        cutoff = now - self.window_ms
        while samples and samples[0][0] < cutoff:
            samples.popleft()
        return list(samples)

    @staticmethod
    def _rate_terms(recent: List[Tuple[float, float]], now: float) -> Tuple[float, float]:
        """Return the measured ``(lambda, mu)`` pair in tasks per millisecond."""

        services = [service for _, service in recent]
        mean_service = float(sum(services) / len(services))
        if mean_service <= 0.0:
            return 0.0, 0.0
        mu = 1.0 / mean_service
        observed = max(min(now - recent[0][0], QUEUE_WINDOW_MS), QUEUE_MIN_WINDOW_MS)
        lam = len(recent) / observed
        return float(lam), float(mu)

    def estimates(self, key: str, now: float) -> Tuple[float, float]:
        """Return ``(rho, T^q)`` of ``key`` at virtual time ``now``.

        A destination with no recent traffic is reported as idle and therefore
        has zero queueing delay.  That optimistic prior is deliberate: it is
        what keeps exploration of the edge tier alive, and it is also what lets
        a node the policy has backed away from become usable again once it has
        drained.
        """

        recent = self._window(key, now)
        if len(recent) < 2:
            return 0.0, 0.0
        lam, mu = self._rate_terms(recent, now)
        if mu <= 0.0:
            return 0.0, 0.0
        rho = min(lam / mu, RHO_MAX)
        tq = rho / max(mu - lam, EPS_Q)
        return float(rho), float(min(tq, QUEUE_WAIT_CAP_MS))

    def wait_ms(self, task, action: int, global_index: int) -> float:
        """Queueing delay a task would incur at ``action`` right now (Eq. 11)."""

        key = self.destination_key(task, action)
        now = self._clock_ms(key, task, global_index)
        return self.estimates(key, now)[1]

    def step(self, task, action: int, service_ms: float, global_index: int) -> float:
        """Commit one task to ``action`` and return its queueing delay."""

        key = self.destination_key(task, action)
        now = self._clock_ms(key, task, global_index)
        if key.startswith("terminal::"):
            station = key[len("terminal::"):]
            self.station_count[station] = self.station_count.get(station, 0) + 1

        # Predict with the history *before* the new sample is folded in.
        recent = self._window(key, now)
        if len(recent) >= 2:
            lam, mu = self._rate_terms(recent, now)
        else:
            lam = len(recent) / QUEUE_MIN_WINDOW_MS
            mu = 1.0 / max(recent[0][1] if recent else float(service_ms), 1e-9)
        rho = min(lam / mu, RHO_MAX) if mu > 0 else 0.0
        tq = min(rho / max(mu - lam, EPS_Q), QUEUE_WAIT_CAP_MS)
        self.rho[key] = float(rho)
        self.tq[key] = float(tq)

        service = self.effective_service_ms(action, service_ms)
        bucket = self.arrivals.setdefault(key, deque())
        bucket.append((now, service))
        cutoff = now - self.window_ms
        while bucket and bucket[0][0] < cutoff:
            bucket.popleft()

        self.served[key] = self.served.get(key, 0) + 1
        self.busy_ms[key] = self.busy_ms.get(key, 0.0) + service
        self.horizon_ms = max(self.horizon_ms, now + service)
        return float(tq)

    # -- observation -----------------------------------------------------
    @staticmethod
    def _clip01(value: float) -> float:
        return float(min(max(value, 0.0), 1.0))

    def destination_load(self, key: str, now: float) -> float:
        if key not in self.arrivals:
            return 0.0
        return self._clip01(self.estimates(key, now)[0])

    def edge_loads(self, now_ms: float = 0.0) -> List[float]:
        return [
            self.destination_load(str(EDGE_NODE_BY_ACTION[a]["name"]), now_ms)
            for a in EDGE_ACTION_IDS
        ]

    def backlog_by_destination(self, task, global_index: int) -> Dict[str, float]:
        return {
            key: self.estimates(key, self._clock_ms(key, task, global_index))[1]
            for key in ACTION_MAP.values()
        }

    def context(self, task, global_index: int) -> Dict[str, float]:
        """Observation of the current system load.

        ``load_*`` entries are the utilisation estimates ``rho_m`` of Eq. (11)
        and are what the agent consumes.  ``backlog_ms_*`` entries are the
        corresponding queueing-delay predictions, which the digital twin prices
        before certifying an action.
        """

        now = float(global_index) * GLOBAL_INTERVAL_MS
        edge = self.edge_loads(now)
        terminal_keys = [k for k in self.arrivals if k.startswith("terminal::")]
        terminal_load = max(
            [
                self.destination_load(k, self._clock_ms(k, task, global_index))
                for k in terminal_keys
            ]
            or [0.0]
        )
        context = {
            "queue_backlog_mean": float(sum(edge) / len(edge)),
            "queue_backlog_max": float(max(edge)),
            "load_edge_1": edge[0],
            "load_edge_2": edge[1],
            "load_edge_3": edge[2],
            "load_cloud": self.destination_load("cloud", now),
            "load_terminal": float(terminal_load),
        }
        for action in ACTION_MAP:
            key = self.destination_key(task, action)
            context[f"backlog_ms_{ACTION_MAP[action]}"] = float(
                self.estimates(key, self._clock_ms(key, task, global_index))[1]
            )
        return context

    def utilisation(self) -> Dict[str, float]:
        """Time-average utilisation per destination over the run horizon."""

        horizon = max(self.horizon_ms, 1e-9)
        return {key: busy / horizon for key, busy in self.busy_ms.items()}

    def rho_by_destination(self) -> Dict[str, float]:
        """Final Eq. (11) utilisation estimate per destination."""

        return dict(self.rho)

    def summary(self) -> Dict[str, float]:
        """Run-level utilisation summary written into every record frame."""

        rho = self.rho_by_destination()
        edge_rho = [rho.get(name, 0.0) for name in EDGE_ACTION_NAMES]
        time_avg = self.utilisation()
        edge_time_avg = [time_avg.get(name, 0.0) for name in EDGE_ACTION_NAMES]
        return {
            "horizon_ms": round(self.horizon_ms, 4),
            "edge_utilisation_mean": round(sum(edge_time_avg) / len(edge_time_avg), 6),
            "edge_utilisation_max": round(max(edge_time_avg), 6),
            "edge_rho_mean": round(sum(edge_rho) / len(edge_rho), 6),
            "edge_rho_max": round(max(edge_rho), 6),
            "cloud_utilisation": round(time_avg.get("cloud", 0.0), 6),
            "terminal_utilisation_mean": round(
                sum(v for k, v in time_avg.items() if k.startswith("terminal::"))
                / max(len([k for k in time_avg if k.startswith("terminal::")]), 1),
                6,
            ),
        }


